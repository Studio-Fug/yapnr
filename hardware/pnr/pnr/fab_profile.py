"""Selectable fabrication-capability profiles (``PNR_FAB_PROFILE``).

One profile is the single source of truth for every fabrication number the
engine uses: the ``rules.json`` ``fab`` block (router grid, native oracles,
KiCad ``.kicad_pro`` board constraints), the electrical/plane-access fab models
(IPC-2221 widths, via-barrel budgets) and the KiCad custom rules
(``<board>.kicad_dru``) that make ``kicad-cli pcb drc`` enforce the PTH / NPTH /
filled-via distinctions KiCad's board constraints cannot express.

Profiles
    ``jlc-pofv`` (default when ``PNR_FAB_PROFILE`` is unset)
        JLCPCB standard 4-layer, 1.6 mm, 1 oz outer / 0.5 oz inner (15.2 um
        finished, stackup JLC04161H-7628) plus epoxy filled & capped vias (POFV)
        on all vias. Values: ``docs/fab-comparison.md`` section 5B on the 5A base;
        each value below cites its row.
    ``legacy``
        The rules as they were before profiles existed. Every function here is
        the identity for it and no ``.kicad_dru`` is written, so
        ``PNR_FAB_PROFILE=legacy`` reproduces the old rules exactly (A/B baseline).

Applied rules carry ``rules['fab_profile'] = <name>`` (never for legacy).
Consuming rules compiled for another profile raises instead of mixing numbers.

Via-in-pad: ``Geometry.in_pad`` (5B filled in-pad class and geometry,
:func:`in_pad_fit` / :func:`in_pad_sites`) and ``Geometry.via_to_smd_pad`` (5A via
copper to SMD pad 0.127) are None for legacy, whose engine keeps its 0.05 mm
via-to-SMD-pad keep-away and never places a via in a pad; pnr.via_in_pad applies
them to native items.
"""
